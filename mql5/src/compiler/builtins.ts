/** RGB 0xRRGGBB → MQL5 colour 0x00BBGGRR. */
export function rgbToMqlColor(rgb: number): number {
  const r = (rgb >> 16) & 0xff;
  const g = (rgb >> 8) & 0xff;
  const b = rgb & 0xff;
  return (b << 16) | (g << 8) | r;
}

