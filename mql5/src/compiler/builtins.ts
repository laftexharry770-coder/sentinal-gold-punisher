/**
 * MQL5's predefined enumerations and constants.
 *
 * Values that programs are known to compare or store (timeframes, order and
 * position types, trade actions and return codes, MA methods, applied prices,
 * init results) carry MetaTrader's real numbers. Property identifiers
 * (SYMBOL_BID, ACCOUNT_BALANCE, …) are only ever passed back into the
 * runtime, so they just need to be distinct within their enumeration.
 */

export type EnumTable = Record<string, [name: string, value: number][]>;

function seq(names: string[], start = 0): [string, number][] {
  return names.map((name, i) => [name, start + i]);
}

